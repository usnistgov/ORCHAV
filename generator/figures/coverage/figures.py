"""
Coverage visualization utilities.

Creates quick-look figures from HDF5 coverage files generated by
``save_coverage_map()``. Coverage v2 files may only store canonical
``path_gain_linear`` plus compact derived labels, so this module derives
plotting layers from recipe metadata instead of assuming every metric is a
physical HDF5 dataset.

The map, metric-guide, and distribution entry points return every generated
path. Each writes one explicitly height-labelled file per stored height, even
when the input contains only one height.
"""

